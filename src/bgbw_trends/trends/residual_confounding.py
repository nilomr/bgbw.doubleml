"""Residual-confounding null diagnostic (Fink 2023 §2.2).

Background
----------
DML removes confounding between year (the treatment) and the species
response by partialling out a propensity score model — a forest that
predicts year from the observer-process features (X_effort) and habitat
features (X_hab).  If the propensity score model is well-specified, the
residuals year - s_hat(X) carry no signal from the confounders and the
causal-forest stage recovers an unbiased trend.

Residual confounding occurs when the propensity model *misses* some
channel through which year predicts the response — e.g. a systematic
change in observer demographics not captured by X_effort, or a land-use
trend that correlates with survey effort.  In that case the estimated
trend is biased: the model would detect a "trend" even in data where no
true trend exists.

Algorithm (§2.2)
----------------
The null diagnostic quantifies this bias via a fully data-driven
simulation:

  1. Resample surveys with replacement, stratified by year, to preserve
     the interannual confounding structure in the original features
     (same year-distribution, same feature-year correlations).
  2. Replace the species response with draws from a zero-trend DGP:
     fit a conditional-mean forest on (X_hab, X_effort) — **no year** —
     obtain OOB predictions (the conditional mean given covariates), add
     parametric-bootstrap noise matching the residual SD.  For the hurdle
     model this is done separately for the binary occurrence stage
     (Bernoulli draw) and the log-count stage (Gaussian noise on detected
     rows).
  3. Refit the full DML pipeline on this null data.
  4. Record the estimated range-wide trend as the spatial median of
     abd_ppy across grid cells: median(τ_occ(W) / P(occ) + τ_count(W)).

By construction the true trend in the null data is zero; any non-zero
estimated trend is pure bias from residual confounding.  Averaging the
null estimates over several independent simulations gives a stable bias
estimate.

This exactly mirrors ``generate_null_trend_model_data`` in
``trendswf/doc/motivating-example.R`` and the vignette
``trendswf/vignettes/motivating-example.Rmd`` (``n_mc <- 100`` null sims).
The key check — that year is absent from the conditional-mean forest —
is guaranteed here because ``_assemble_X(df, None)`` only includes
HABITAT_FEATURES + EFFORT_FEATURES (see ``config.py``), not year.

Bias correction (Fink §2.2 / vignette)
---------------------------------------
Both the raw ensemble trend and the null-sim trend use the same summary
statistic: the spatial median of abd_ppy over grid cells.  The correction
subtracts like from like:

    corrected_range_wide_trend ≈ raw_trend − bias_ate_abd

where ``raw_trend = np.nanmedian(ensemble.abd_ppy)`` (median across cells,
then median across ensemble members) and ``bias_ate_abd`` is the mean of
``np.nanmedian(abd_ppy)`` across null simulations.

SE propagation: the vignette simulation study shows that combining the
real SE and the null SD in quadrature is a conservative but sensible
approach (both are independent Gaussian noise):

    corrected_SE ≈ sqrt(real_SE² + null_SD²)

where ``null_SD = std(sim_ate_abd)`` from the ``ResidualConfoundingResult``.

Output files (written by the pipeline script)
---------------------------------------------
``adjustment.json``
    Scalar bias estimates (bias_ate_occ, bias_ate_count, bias_ate_abd)
    and metadata (n_successful, n_simulations).  Load this file and
    apply the correction post-hoc:

        import json, numpy as np
        adj = json.load(open("rc/blackbird/adjustment.json"))
        corrected = raw_abd_ppy_median - adj["bias_ate_abd"]

``simulations.parquet``
    Long-format per-simulation × per-cell table (sim_idx, bng_ref,
    occ_ppy, count_ppy, abd_ppy).  Used for spatial bias diagnostics:
    are some regions systematically over- or under-estimated in the
    null?  Per-cell correction is not validated by Fink and should be
    treated as exploratory.

Limitations
-----------
* The null bias is a scalar; the correction assumes confounding affects
  all grid cells equally.  If confounding is spatially heterogeneous the
  range-wide correction is correct in expectation but per-cell
  corrections are unreliable.
* 5 null simulations (the script default) give a coarse bias estimate.
  Use ≥25 for a usable bias estimate; 100 (Fink's reference) for
  publication-grade results.
* This is intentionally the §2.2 null-only diagnostic, NOT the extended
  multi-scenario calibration regression from §3.4/§3.5.  The §3.4
  extension fits a per-cell regression of (estimated trend) ~ (true
  trend) across 50+ training scenarios generated by a population-dynamics
  DGP with spatially varying true trends (core-edge gradient).  It
  requires substantially more compute and a bespoke simulation study;
  see docs/refrence/fink_2023.txt §3.4 and science_sm.txt §3.5 for
  details.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field, replace

import numpy as np
import pandas as pd

from bgbw_trends.config import ReferenceEffort, RunConfig
from bgbw_trends.pipeline import (
    _assemble_X,
    _fit_nuisance,
    _predict,
    train_predict_species,
)
from bgbw_trends.trends.ensemble import split_cell_years

logger = logging.getLogger(__name__)

_NULL_DGP_MAX_TREES = 100


# ── Result container ──────────────────────────────────────────────────────────


@dataclass
class ResidualConfoundingResult:
    """Null-simulation diagnostics for one species.

    bias_ate_occ, bias_ate_count
        Mean range-wide ATE across null simulations for the occurrence and
        count stages.  Units: probability/yr and log-count/yr respectively.
        Values far from zero indicate residual confounding that the
        propensity score model did not absorb.
    bias_ate_abd
        Mean range-wide median abd_ppy across null simulations (%/yr as a
        ratio).  Interpretable headline: how much trend the model estimates
        when the true trend is zero.
        Directional correction: corrected = raw_abd_ppy − bias_ate_abd.
    sim_df
        Long-format DataFrame (one row per simulation × cell):
        ``sim_idx``, ``bng_ref``, ``occ_ppy``, ``count_ppy``, ``abd_ppy``.
        Saved to simulations.parquet for spatial bias diagnostics.
    n_successful
        Number of null simulations that completed without error.
    """

    species: str
    bias_ate_occ: float
    bias_ate_count: float
    bias_ate_abd: float
    n_successful: int
    sim_df: pd.DataFrame
    sim_ate_occ: np.ndarray = field(default_factory=lambda: np.array([]))
    sim_ate_count: np.ndarray = field(default_factory=lambda: np.array([]))
    sim_ate_abd: np.ndarray = field(default_factory=lambda: np.array([]))


# ── Null DGP ──────────────────────────────────────────────────────────────────


def _null_species_values(
    df: pd.DataFrame,
    species: str,
    cfg: RunConfig,
    rng: np.random.Generator,
    n_jobs: int = -1,
) -> np.ndarray:
    """Regenerate the species column under a zero-trend DGP.

    Follows Fink §2.2 / trendswf vignette motivating-example.Rmd:
    fit a forest on the resampled features (year excluded by default in
    _assemble_X), use OOB predictions as the conditional mean, add
    parametric-bootstrap noise.  Adapted to the hurdle: Bernoulli draw
    for occurrence, log-normal noise for log-counts on detected rows.
    """
    X = _assemble_X(df, None)
    null_cfg = replace(cfg, n_estimators=min(cfg.n_estimators, _NULL_DGP_MAX_TREES))

    y_bin = (df[species] > 0).to_numpy(dtype=np.float64)
    _occ_forest, p_hat = _fit_nuisance(
        X, y_bin, null_cfg, seed=int(rng.integers(0, 2**31)), n_jobs=n_jobs
    )
    p_hat = np.clip(p_hat, 0.0, 1.0)
    y_bin_null = rng.binomial(1, p_hat).astype(np.float64)

    count_null = np.zeros(len(df), dtype=np.float64)
    orig_detected = y_bin > 0
    if orig_detected.sum() < 50:
        return count_null

    Y_log = np.log1p(df.loc[orig_detected, species].to_numpy(dtype=np.float64))
    X_det = X.iloc[orig_detected.nonzero()[0]].reset_index(drop=True)
    _count_forest, m_count_oof = _fit_nuisance(
        X_det,
        Y_log,
        null_cfg,
        seed=int(rng.integers(0, 2**31)),
        n_jobs=n_jobs,
    )
    resid_sd = float(np.std(Y_log - m_count_oof, ddof=0))

    m_count_all = _predict(_count_forest, X)
    noise = rng.normal(0.0, resid_sd, size=len(df))
    log_count_null = m_count_all + noise
    count_null = np.where(
        y_bin_null > 0, np.maximum(np.expm1(log_count_null), 0.0), 0.0
    )
    return count_null


# ── Per-simulation worker ─────────────────────────────────────────────────────


def _one_null_simulation(
    df: pd.DataFrame,
    species: str,
    cfg: RunConfig,
    grid: pd.DataFrame,
    reference_effort: ReferenceEffort,
    sim_idx: int,
    sim_seed: int,
    n_jobs: int,
    n_total: int = 0,
) -> dict | None:
    """One null-trend simulation (§2.2).

    Returns a dict with keys:
      bng_ref, occ_ppy, count_ppy, abd_ppy  (per-cell arrays)
      ate_occ, ate_count                     (scalar ATEs for diagnostics)
      abd_median                             (range-wide median abd_ppy)
    or None on failure.
    """
    label = f"{sim_idx + 1}/{n_total}" if n_total else str(sim_idx + 1)
    logger.info("Null sim %s starting [%s]", label, species)
    if cfg.sim_n_estimators > 0:
        cfg = replace(cfg, n_estimators=cfg.sim_n_estimators, cf_n_estimators=cfg.sim_n_estimators)
    rng = np.random.default_rng(sim_seed)
    years = df["year"].to_numpy()
    unique_years = np.unique(years)

    # Step 1 — stratified bootstrap (preserves interannual confounding)
    pieces = [
        rng.choice(np.where(years == y)[0], size=int((years == y).sum()), replace=True)
        for y in unique_years
    ]
    boot_idx = np.concatenate(pieces)
    null_df = df.iloc[boot_idx].reset_index(drop=True)

    # Step 2 — zero-trend DGP
    null_df[species] = _null_species_values(null_df, species, cfg, rng, n_jobs=n_jobs)

    # Step 3 — 50/50 split matching ensemble, refit pipeline
    occ_df, count_df = split_cell_years(null_df, rng)

    try:
        pred = train_predict_species(
            occ_df,
            count_df,
            species=species,
            cfg=cfg,
            grid=grid,
            reference_effort=reference_effort,
            seed=int(rng.integers(0, 2**31)),
            n_jobs=n_jobs,
        )
    except Exception as e:  # noqa: BLE001
        logger.warning("Null sim %s failed [%s]: %s", label, species, e)
        return None

    logger.info("Null sim %s done [%s]", label, species)
    return {
        "bng_ref": pred.bng_ref,
        "occ_ppy": pred.occ_ppy,
        "count_ppy": pred.count_ppy,
        "abd_ppy": pred.abd_ppy,
        "ate_occ": float(pred.ate_occ),
        "ate_count": float(pred.ate_count),
        "abd_median": float(np.nanmedian(pred.abd_ppy)),
    }


# ── Public API ────────────────────────────────────────────────────────────────


def diagnose_residual_confounding(
    df: pd.DataFrame,
    *,
    species: str,
    cfg: RunConfig,
    grid: pd.DataFrame,
    reference_effort: ReferenceEffort,
    n_simulations: int = 5,
    seed: int = 0,
) -> ResidualConfoundingResult:
    """Run null-trend simulations and report the residual confounding bias.

    Parameters
    ----------
    df
        Training frame — same as passed to ``train_predict_species``.
    species
        Species column name.
    cfg, grid, reference_effort
        Passed through to ``train_predict_species``.
    n_simulations
        Number of independent null simulations.  Each is one full pipeline
        fit on bootstrapped null data.  5–10 is sufficient for diagnostics;
        more gives a more stable bias estimate.
    seed
        Base RNG seed.
    """
    logger.info(
        "Residual confounding null diagnostic [%s]: %d simulation(s)",
        species,
        n_simulations,
    )

    seed_seq = np.random.SeedSequence(seed)
    child_seeds = seed_seq.spawn(n_simulations)

    # Cap workers to the number of jobs — joblib spawns min(n_jobs, len(tasks))
    # processes, so requesting more workers than tasks causes inner threads to be
    # under-provisioned (cpu_count // n_workers instead of cpu_count // actual_workers).
    n_workers = min(max(1, cfg.n_workers), n_simulations)
    worker_n_jobs = cfg.effective_n_jobs(n_workers)

    jobs = [
        (
            df,
            species,
            cfg,
            grid,
            reference_effort,
            i,
            int(child_seeds[i].generate_state(1)[0]),
            worker_n_jobs,
            n_simulations,
        )
        for i in range(n_simulations)
    ]

    if n_workers == 1:
        results_raw = []
        for args in jobs:
            results_raw.append(_one_null_simulation(*args))
            logger.info(
                "RC null sims: %d/%d complete [%s]", len(results_raw), n_simulations, species
            )
    else:
        from joblib import Parallel, delayed

        logger.info(
            "RC null sims: %d parallel workers  •  %d threads/worker",
            n_workers,
            worker_n_jobs,
        )
        _gen = Parallel(n_jobs=n_workers, backend="loky", verbose=0, return_as="generator_unordered")(
            delayed(_one_null_simulation)(*args) for args in jobs
        )
        results_raw = []
        for r in _gen:
            results_raw.append(r)
            logger.info(
                "RC null sims: %d/%d complete [%s]", len(results_raw), n_simulations, species
            )

    sim_records: list[pd.DataFrame] = []
    ate_occ_list: list[float] = []
    ate_count_list: list[float] = []
    abd_median_list: list[float] = []
    n_ok = 0

    for sim_idx, result in enumerate(results_raw):
        if result is None:
            continue
        n_ok += 1
        bng_ref = result["bng_ref"]
        n_cells = len(bng_ref)
        sim_records.append(
            pd.DataFrame(
                {
                    "sim_idx": np.full(n_cells, sim_idx, dtype=np.int32),
                    "bng_ref": bng_ref,
                    "occ_ppy": result["occ_ppy"],
                    "count_ppy": result["count_ppy"],
                    "abd_ppy": result["abd_ppy"],
                }
            )
        )
        ate_occ_list.append(result["ate_occ"])
        ate_count_list.append(result["ate_count"])
        abd_median_list.append(result["abd_median"])

    if n_ok == 0:
        logger.warning("All null RC simulations failed")
        return ResidualConfoundingResult(
            species=species,
            bias_ate_occ=float("nan"),
            bias_ate_count=float("nan"),
            bias_ate_abd=float("nan"),
            n_successful=0,
            sim_df=pd.DataFrame(),
        )

    sim_df = pd.concat(sim_records, ignore_index=True)
    sim_ate_occ = np.asarray(ate_occ_list)
    sim_ate_count = np.asarray(ate_count_list)
    sim_ate_abd = np.asarray(abd_median_list)

    bias_ate_occ = float(np.mean(sim_ate_occ))
    bias_ate_count = float(np.mean(sim_ate_count))
    bias_ate_abd = float(np.mean(sim_ate_abd))

    logger.info(
        "RC null-bias [%s]: occ=%+.4f (sd=%.4f)  count=%+.4f (sd=%.4f)"
        "  abd=%+.4f (sd=%.4f)  n=%d/%d",
        species,
        bias_ate_occ,
        float(np.std(sim_ate_occ)) if n_ok > 1 else 0.0,
        bias_ate_count,
        float(np.std(sim_ate_count)) if n_ok > 1 else 0.0,
        bias_ate_abd,
        float(np.std(sim_ate_abd)) if n_ok > 1 else 0.0,
        n_ok,
        n_simulations,
    )

    return ResidualConfoundingResult(
        species=species,
        bias_ate_occ=bias_ate_occ,
        bias_ate_count=bias_ate_count,
        bias_ate_abd=bias_ate_abd,
        n_successful=n_ok,
        sim_df=sim_df,
        sim_ate_occ=sim_ate_occ,
        sim_ate_count=sim_ate_count,
        sim_ate_abd=sim_ate_abd,
    )
